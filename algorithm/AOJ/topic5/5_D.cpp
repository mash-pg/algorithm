#include <iostream>
using namespace std;

int main() {
    int n;
    cin >> n;   // 出力する上限値 n を入力

    /*
     * =========================================================
     * 【プログラムの目的】
     * ---------------------------------------------------------
     * 1 ～ n までの数を順番に調べ、
     * ・3 の倍数
     * ・または 数字のどこかに「3」を含む数
     * を出力する。
     *
     * 元の goto 文を使った処理を、
     * for / while / continue / break に置き換えたもの。
     * =========================================================
     */

    /*
     * ---------------------------------------------------------
     * 【外側ループ】
     * ---------------------------------------------------------
     * i = 1 ～ n まで、1 つずつ数を調べる。
     * goto 版の「CHECK_NUM」ラベルに相当。
     */
    for (int i = 1; i <= n; i++) {

        /*
         * -----------------------------------------------------
         * 【条件①：3 の倍数か？】
         * -----------------------------------------------------
         * i % 3 == 0 の場合は必ず出力する。
         * 出力後は continue により、
         * 「3 を含むかどうか」の判定を省略して次の i へ。
         *
         * goto 版の：
         *   if (x % 3 == 0) goto END_CHECK_NUM;
         * に相当。
         */
        if (i % 3 == 0) {
            cout << " " << i;
            continue;
        }

        /*
         * -----------------------------------------------------
         * 【条件②：数字のどこかに 3 を含むか？】
         * -----------------------------------------------------
         * 元の値 i を壊さないため、x にコピーして桁チェックを行う。
         */
        int x = i;

        /*
         * -----------------------------------------------------
         * 【内側ループ（桁チェック）】
         * -----------------------------------------------------
         * x が 0 になるまで、
         * 右端の桁から順に調べる。
         *
         * goto 版の「INCLUDE3」ラベルを
         * while ループに置き換えたもの。
         */
        while (x > 0) {

            /*
             * x % 10 で現在の一番右の桁を取得。
             * それが 3 であれば、元の数 i を出力して終了。
             *
             * goto 版の：
             *   if (x % 10 == 3) goto END_CHECK_NUM;
             * に相当。
             */
            if (x % 10 == 3) {
                cout << " " << i;
                break;  // 桁チェック終了
            }

            /*
             * 次の桁へ進む。
             * 例：
             *   123 → 12 → 1 → 0
             */
            x /= 10;
        }
    }

    // 出力の最後に改行を入れる（問題仕様）
    cout << endl;
    return 0;
}
